package collector

import (
	"context"
	"fmt"
	"io/fs"
	"path"
	"regexp"
	"strings"
	"unicode"
)

const (
	postfixMainCF         = "/etc/postfix/main.cf"
	dovecotConfig         = "/etc/dovecot/dovecot.conf"
	pleskPanelCertificate = "/usr/local/psa/admin/conf/httpsd.pem"
	directAdminConfig     = "/usr/local/directadmin/conf"

	// maxServiceConfigFile bounds one mail or panel configuration file.
	maxServiceConfigFile = 1 << 20
	// serviceIncludeDepth and serviceIncludeFiles bound the includes
	// followed in a Dovecot or Exim configuration.
	serviceIncludeDepth = 4
	serviceIncludeFiles = 64
)

// eximConfigs are the main Exim configuration files, in the order tried:
// EL, DirectAdmin and cPanel's /etc/exim.conf, then Debian's generated
// configuration and its non-template file.
var eximConfigs = []string{"/etc/exim.conf", "/etc/exim/exim.conf", "/var/lib/exim4/config.autogenerated", "/etc/exim4/exim4.conf"}

// postfixParameters are the certificate parameters read from Postfix.
// smtpd_tls_chain_files, when set, replaces the other two; each of its
// files holds a key followed by a certificate chain.
var postfixParameters = []string{"smtpd_tls_cert_file", "smtpd_tls_eccert_file", "smtpd_tls_chain_files"}

// serviceCertificate is a certificate file a service is configured with.
type serviceCertificate struct {
	kind, ref   string
	path, chain string
}

// serviceCertificates returns the certificate files of Postfix, Dovecot,
// Exim and the Plesk and DirectAdmin panels.
func serviceCertificates(ctx context.Context, run *certificateRun) []serviceCertificate {
	var result []serviceCertificate
	result = append(result, postfixCertificates(ctx, run)...)
	result = append(result, dovecotCertificates(run)...)
	result = append(result, eximCertificates(run)...)
	result = append(result, panelCertificates(run)...)
	return result
}

// readServiceConfig reads a configuration file with the size and symlink
// policy, warning about anything but a missing or unreadable file.
func (run *certificateRun) readServiceConfig(name string) ([]byte, bool) {
	data, err := run.host.readBoundedFile(name, maxServiceConfigFile)
	if err != nil {
		if warning := certificateWarning(name, err); warning != "" {
			run.warn(warning)
		}
		return nil, false
	}
	return data, true
}

// postfixCertificates reads the certificate parameters with postconf, or
// from main.cf when postconf is not available.
func postfixCertificates(ctx context.Context, run *certificateRun) []serviceCertificate {
	host := run.host
	var parameters map[string]string
	if postconf := host.findCommand("postconf"); postconf != "" && host.Command != nil {
		values, err := postconfValues(ctx, host, postconf)
		if err != nil {
			run.warn("postfix: " + err.Error())
		} else {
			parameters = values
		}
	}
	if parameters == nil {
		if !host.exists(postfixMainCF) {
			return nil
		}
		data, ok := run.readServiceConfig(postfixMainCF)
		if !ok {
			return nil
		}
		parameters = parsePostfixMainCF(data)
	}
	files := postfixListFields(expandPostfix(parameters["smtpd_tls_chain_files"], parameters))
	if len(files) == 0 {
		for _, name := range []string{"smtpd_tls_cert_file", "smtpd_tls_eccert_file"} {
			if value := expandPostfix(parameters[name], parameters); value != "" {
				files = append(files, value)
			}
		}
	}
	var result []serviceCertificate
	for _, name := range files {
		if path.IsAbs(name) {
			result = append(result, serviceCertificate{kind: CertificateUsePostfix, ref: "postfix", path: name})
		}
	}
	return result
}

// postconfValues runs postconf for postfixParameters. -x expands $name
// references (Postfix 2.10+); older releases are asked again without it.
// The name = value form, unlike -h, stays unambiguous when a release does
// not know one of the parameters.
func postconfValues(ctx context.Context, host *Host, postconf string) (map[string]string, error) {
	result, err := host.run(ctx, postconf, append([]string{"-x"}, postfixParameters...)...)
	if err == nil && result.ExitCode != 0 {
		result, err = host.run(ctx, postconf, postfixParameters...)
	}
	if err != nil {
		return nil, fmt.Errorf("postconf: %w", err)
	}
	if result.ExitCode != 0 {
		return nil, fmt.Errorf("postconf exited with status %d: %s", result.ExitCode, firstLine(result.Stderr))
	}
	values := map[string]string{}
	for _, line := range lines(result.Stdout) {
		name, value, ok := strings.Cut(line, "=")
		if ok {
			values[strings.TrimSpace(name)] = strings.TrimSpace(value)
		}
	}
	return values, nil
}

// parsePostfixMainCF parses main.cf: name = value lines, continued by lines
// that start with whitespace.
func parsePostfixMainCF(data []byte) map[string]string {
	parameters := map[string]string{}
	name := ""
	for _, line := range lines(data) {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}
		if line[0] == ' ' || line[0] == '\t' {
			if name != "" {
				parameters[name] = strings.TrimSpace(parameters[name] + " " + trimmed)
			}
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			name = ""
			continue
		}
		name = strings.TrimSpace(key)
		parameters[name] = strings.TrimSpace(value)
	}
	return parameters
}

var postfixReference = regexp.MustCompile(`\$(?:\{([A-Za-z0-9_]+)\}|\(([A-Za-z0-9_]+)\)|([A-Za-z0-9_]+))`)

// expandPostfix replaces $name, ${name} and $(name) references with their
// values (config_directory defaults to /etc/postfix), up to 8 levels. It
// returns "" when a reference cannot be resolved.
func expandPostfix(value string, parameters map[string]string) string {
	for range 8 {
		if !strings.Contains(value, "$") {
			return value
		}
		unresolved := false
		value = postfixReference.ReplaceAllStringFunc(value, func(reference string) string {
			match := postfixReference.FindStringSubmatch(reference)
			name := match[1] + match[2] + match[3]
			if replacement, ok := parameters[name]; ok {
				return replacement
			}
			if name == "config_directory" {
				return "/etc/postfix"
			}
			unresolved = true
			return reference
		})
		if unresolved {
			return ""
		}
	}
	return ""
}

// postfixListFields splits a Postfix list on commas and whitespace.
func postfixListFields(value string) []string {
	return strings.FieldsFunc(value, func(character rune) bool { return character == ',' || unicode.IsSpace(character) })
}

// dovecotCertificates reads ssl_cert = <path (and ssl_alt_cert, and
// Dovecot 2.4's ssl_server_cert_file) from dovecot.conf and its
// !include / !include_try files.
func dovecotCertificates(run *certificateRun) []serviceCertificate {
	if !run.host.exists(dovecotConfig) {
		return nil
	}
	var found []string
	budget := serviceIncludeFiles
	run.dovecotFile(dovecotConfig, 0, &budget, &found)
	result := make([]serviceCertificate, 0, len(found))
	for _, name := range found {
		result = append(result, serviceCertificate{kind: CertificateUseDovecot, ref: "dovecot", path: name})
	}
	return result
}

func (run *certificateRun) dovecotFile(name string, depth int, budget *int, found *[]string) {
	data, ok := run.readServiceConfig(name)
	if !ok {
		return
	}
	for _, raw := range lines(data) {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if pattern, ok := cutDirective(line, "!include_try", "!include"); ok {
			run.followIncludes(absoluteFrom(path.Dir(name), unquote(pattern)), depth, budget, func(included string) {
				run.dovecotFile(included, depth+1, budget, found)
			})
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		value = unquote(strings.TrimSpace(value))
		switch strings.TrimSpace(key) {
		case "ssl_cert", "ssl_alt_cert":
			// Older Dovecot reads the file named after "<".
			if file, isFile := strings.CutPrefix(value, "<"); isFile {
				addConfiguredPath(found, absoluteFrom(path.Dir(name), unquote(strings.TrimSpace(file))))
			}
		case "ssl_server_cert_file", "ssl_server_alt_cert_file":
			addConfiguredPath(found, absoluteFrom(path.Dir(name), unquote(value)))
		}
	}
}

// cutDirective returns the argument of a line that starts with one of the
// directives (checked in order) followed by whitespace.
func cutDirective(line string, directives ...string) (string, bool) {
	for _, directive := range directives {
		if rest, ok := strings.CutPrefix(line, directive); ok && rest != "" && (rest[0] == ' ' || rest[0] == '\t') {
			return strings.TrimSpace(rest), true
		}
	}
	return "", false
}

// followIncludes expands an include glob and visits each match within the
// depth and file budget.
func (run *certificateRun) followIncludes(pattern string, depth int, budget *int, visit func(string)) {
	if depth+1 > serviceIncludeDepth {
		run.warn(fmt.Sprintf("%s: not followed, more than %d include levels", pattern, serviceIncludeDepth))
		return
	}
	matches, err := fs.Glob(run.host.FS, relative(pattern))
	if err != nil {
		return
	}
	for _, match := range matches {
		if *budget <= 0 {
			run.warn(fmt.Sprintf("%s: not followed, more than %d included files", "/"+match, serviceIncludeFiles))
			return
		}
		if run.host.isDir(match) {
			continue
		}
		*budget--
		visit("/" + match)
	}
}

func addConfiguredPath(found *[]string, name string) {
	if name != "" && path.IsAbs(name) && !strings.Contains(name, "$") && !strings.Contains(name, "%") {
		*found = append(*found, name)
	}
}

// eximCertificates reads tls_certificate from the main section of the
// first Exim configuration found, resolving macros and .ifdef blocks and
// following .include files.
func eximCertificates(run *certificateRun) []serviceCertificate {
	for _, name := range eximConfigs {
		if !run.host.exists(name) {
			continue
		}
		parser := &eximParser{run: run, macros: map[string]string{}, main: true, budget: serviceIncludeFiles}
		parser.file(name, 0)
		result := make([]serviceCertificate, 0, len(parser.found))
		for _, file := range parser.found {
			result = append(result, serviceCertificate{kind: CertificateUseExim, ref: "exim", path: file})
		}
		return result
	}
	return nil
}

type eximCondition struct {
	active, taken bool
}

type eximParser struct {
	run        *certificateRun
	macros     map[string]string
	conditions []eximCondition
	main       bool
	budget     int
	found      []string
}

var (
	eximMacroDefinition = regexp.MustCompile(`^([A-Z][A-Za-z0-9_]*)\s*==?\s*(.*)$`)
	eximMacroName       = regexp.MustCompile(`[A-Z][A-Za-z0-9_]*`)
)

func (parser *eximParser) active() bool {
	for _, condition := range parser.conditions {
		if !condition.active {
			return false
		}
	}
	return true
}

// parentActive reports whether the conditions around the innermost one
// hold.
func (parser *eximParser) parentActive() bool {
	for _, condition := range parser.conditions[:len(parser.conditions)-1] {
		if !condition.active {
			return false
		}
	}
	return true
}

// substitute replaces defined macro names, up to 8 passes.
func (parser *eximParser) substitute(value string) string {
	for range 8 {
		changed := false
		value = eximMacroName.ReplaceAllStringFunc(value, func(name string) string {
			if replacement, ok := parser.macros[name]; ok {
				changed = true
				return replacement
			}
			return name
		})
		if !changed {
			break
		}
	}
	return value
}

func (parser *eximParser) file(name string, depth int) {
	data, ok := parser.run.readServiceConfig(name)
	if !ok {
		return
	}
	for _, line := range joinBackslashContinuations(lines(data)) {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, ".") && parser.conditional(line) {
			continue
		}
		if !parser.active() {
			continue
		}
		if file, ok := cutDirective(line, ".include_if_exists", ".include"); ok {
			file = parser.substitute(file)
			if !path.IsAbs(file) {
				continue
			}
			parser.run.followIncludes(file, depth, &parser.budget, func(included string) {
				parser.file(included, depth+1)
			})
			continue
		}
		if !parser.main {
			continue
		}
		if line == "begin" || strings.HasPrefix(line, "begin ") {
			// The main section ends at the first "begin" (acl, routers…).
			parser.main = false
			continue
		}
		if match := eximMacroDefinition.FindStringSubmatch(line); match != nil {
			parser.macros[match[1]] = parser.substitute(match[2])
			continue
		}
		key, value, ok := strings.Cut(parser.substitute(line), "=")
		if !ok || strings.TrimSpace(key) != "tls_certificate" || strings.Contains(value, "$") {
			// String expansions (per-SNI certificates) are not evaluated.
			continue
		}
		// A list of certificates (RSA and ECDSA) is colon separated.
		for _, file := range strings.Split(strings.TrimSpace(value), ":") {
			addConfiguredPath(&parser.found, strings.TrimSpace(file))
		}
	}
}

// conditional applies .ifdef, .ifndef, .elifdef, .elifndef, .else and
// .endif, and reports whether line was one of them.
func (parser *eximParser) conditional(line string) bool {
	fields := strings.Fields(line)
	directive, argument := fields[0], ""
	if len(fields) > 1 {
		argument = fields[1]
	}
	_, defined := parser.macros[argument]
	switch directive {
	case ".ifdef", ".ifndef":
		parser.conditions = append(parser.conditions, eximCondition{})
		if parser.parentActive() && defined == (directive == ".ifdef") {
			parser.conditions[len(parser.conditions)-1] = eximCondition{active: true, taken: true}
		}
	case ".elifdef", ".elifndef", ".else":
		if len(parser.conditions) == 0 {
			return true
		}
		top := &parser.conditions[len(parser.conditions)-1]
		matches := directive == ".else" || defined == (directive == ".elifdef")
		top.active = !top.taken && parser.parentActive() && matches
		top.taken = top.taken || top.active
	case ".endif":
		if len(parser.conditions) > 0 {
			parser.conditions = parser.conditions[:len(parser.conditions)-1]
		}
	default:
		return false
	}
	return true
}

// joinBackslashContinuations joins lines that end in a backslash with the
// next one.
func joinBackslashContinuations(physical []string) []string {
	var result []string
	for index := 0; index < len(physical); index++ {
		line := physical[index]
		for strings.HasSuffix(line, "\\") && index+1 < len(physical) {
			index++
			line = strings.TrimSuffix(line, "\\") + strings.TrimSpace(physical[index])
		}
		result = append(result, line)
	}
	return result
}

// panelCertificates returns the certificates of the panels' own web
// interfaces: Plesk's httpsd.pem (which holds the key as well; it is
// skipped while scanning) and DirectAdmin's cacert from directadmin.conf,
// with its carootcert chain.
func panelCertificates(run *certificateRun) []serviceCertificate {
	host := run.host
	var result []serviceCertificate
	if host.exists(pleskPanelCertificate) {
		result = append(result, serviceCertificate{kind: CertificateUsePanel, ref: CertificateToolPlesk, path: pleskPanelCertificate})
	}
	if host.isDir(directAdminConfig) {
		settings := map[string]string{}
		if data, ok := run.readServiceConfig(directAdminConfig + "/directadmin.conf"); ok {
			settings = parseKeyValue(data)
		}
		certificate := settings["cacert"]
		if certificate == "" {
			certificate = directAdminConfig + "/cacert.pem"
		}
		chain := settings["carootcert"]
		if chain == "" && host.exists(directAdminConfig+"/carootcert.pem") {
			chain = directAdminConfig + "/carootcert.pem"
		}
		if path.IsAbs(certificate) && host.exists(certificate) {
			result = append(result, serviceCertificate{kind: CertificateUsePanel, ref: CertificateToolDirectAdmin, path: certificate, chain: chain})
		}
	}
	return result
}
